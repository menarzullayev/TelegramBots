"""Download the Mini App fonts once and emit the @font-face block (self-hosting, no Google at runtime).

Usage (from the tezmafia directory):  python -m scripts.fetch_fonts

Reads the Google Fonts CSS2 API with a modern User-Agent (so it answers with woff2 + unicode-range subsets),
keeps latin / latin-ext / cyrillic / cyrillic-ext, saves the files under assets/fonts/ and rewrites the region
between the FONTS:BEGIN / FONTS:END markers in tezmafia/webapp/static/index.html. Only weights the themes use.
"""

from __future__ import annotations

import re
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "assets" / "fonts"
INDEX = ROOT / "tezmafia" / "webapp" / "static" / "index.html"
UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0.0.0 Safari/537.36"
SUBSETS = ("latin", "latin-ext", "cyrillic", "cyrillic-ext")

# family -> weights actually used by the five themes (dossier, neon, deco, day, comic)
FAMILIES: dict[str, list[int]] = {
    "Old Standard TT": [400, 700],
    "PT Mono": [400],
    "Exo 2": [400, 600, 800],
    "JetBrains Mono": [400, 700],
    "Poiret One": [400],
    "Jost": [400, 500, 600],
    "Manrope": [500, 700, 800],
    "Inter": [400, 500, 600, 700],
    "Oswald": [500, 700],
    "PT Serif": [400, 700],
    "Roboto Condensed": [400, 700],
}

BLOCK = re.compile(r"/\*\s*([\w-]+)\s*\*/\s*@font-face\s*\{(.*?)\}", re.S)


def get(url: str) -> bytes:
    with urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent": UA}), timeout=60) as r:
        return r.read()


def slug(name: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")


def faces(family: str, weights: list[int]) -> list[dict[str, str | list[int]]]:
    spec = f"family={family.replace(' ', '+')}:wght@{';'.join(map(str, weights))}"
    css = get(f"https://fonts.googleapis.com/css2?{spec}&display=swap").decode()
    grouped: dict[tuple[str, str], dict[str, str | list[int]]] = {}
    for subset, body in BLOCK.findall(css):
        if subset not in SUBSETS:
            continue
        url = re.search(r"url\((https://[^)]+\.woff2)\)", body).group(1)  # type: ignore[union-attr]
        weight = int(re.search(r"font-weight:\s*(\d+)", body).group(1))  # type: ignore[union-attr]
        rng = re.search(r"unicode-range:\s*([^;]+);", body).group(1).strip()  # type: ignore[union-attr]
        entry = grouped.setdefault((subset, url), {"subset": subset, "url": url, "range": rng, "weights": []})
        entry["weights"].append(weight)  # type: ignore[union-attr]
    return list(grouped.values())


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    css: list[str] = []
    total = 0
    for family, weights in FAMILIES.items():
        for f in faces(family, weights):
            ws = sorted(f["weights"])  # type: ignore[arg-type]
            tag = f"{ws[0]}" if len(ws) == 1 else f"{ws[0]}-{ws[-1]}"
            name = f"{slug(family)}-{f['subset']}-{tag}.woff2"
            data = get(str(f["url"]))
            (OUT / name).write_bytes(data)
            total += len(data)
            css.append(
                f"@font-face{{font-family:\"{family}\";font-style:normal;font-weight:{ws[0] if len(ws) == 1 else f'{ws[0]} {ws[-1]}'};"
                f"font-display:swap;src:url(/assets/fonts/{name}) format(\"woff2\");unicode-range:{f['range']}}}"
            )
            print(f"{name}  {len(data) // 1024} KB")
    block = "/* FONTS:BEGIN (generated by scripts/fetch_fonts.py) */\n" + "\n".join(css) + "\n/* FONTS:END */"
    html = INDEX.read_text(encoding="utf-8")
    new, n = re.subn(r"/\* FONTS:BEGIN.*?FONTS:END \*/", lambda _m: block, html, flags=re.S)
    if n != 1:
        raise SystemExit("FONTS:BEGIN/END markers not found exactly once in index.html")
    INDEX.write_text(new, encoding="utf-8", newline="\n")
    print(f"total {total // 1024} KB in {len(css)} files")


if __name__ == "__main__":
    main()
